/**
 * Regenerates src/lib/clinic-directory.ts from Clalit's own public clinic directory
 * (https://nearme.clalit.co.il/c.json — the dataset behind every result row's "הצגת מפה" link,
 * which points at nearme.clalit.co.il/nav/<code>).
 *
 * Committed as static data so the extension can (a) list a searched city's Smile branches even when
 * Tamuz has no bookable diary for them, and (b) rank rows by the user's LIVE location — with zero
 * runtime network calls, no background script and no extra host permissions. Re-run when Clalit
 * opens/moves clinics: `npx tsx scripts/fetch-clinic-coords.ts`.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SOURCE_URL = "https://nearme.clalit.co.il/c.json";
const DENTAL_CATEGORY = 111; // "מרפאת שיניים"
const SMILE_TITLE_MARKER = "סמייל";
const OUTPUT_PATH = resolve(import.meta.dirname, "..", "src", "lib", "clinic-directory.ts");

/** Wire shape of c.json: `m` = column names, `u` = rows as positional arrays zipped with `m`. */
type DirectoryPayload = {
  /** Column names for the packed rows. */
  m: string[];
} & Record<"u", unknown[][]>;

interface DirectoryClinic {
  code: number;
  title: string;
  categories: number;
  address: [string, string?] | null;
  phones: string[] | null;
  latlng: [number, number] | null;
}

/** The rows are zipped from the payload's own column list — trust the declared clinic shape. */
function isDirectoryClinic(value: unknown): value is DirectoryClinic {
  return value !== null && typeof value === "object";
}

function decodeRows(payload: DirectoryPayload): DirectoryClinic[] {
  const clinics: DirectoryClinic[] = [];
  for (const values of payload.u) {
    const row: Record<string, unknown> = {};
    payload.m.forEach((key, index) => {
      row[key] = values[index];
    });

    if (isDirectoryClinic(row)) {
      clinics.push(row);
    }
  }

  return clinics;
}

function quote(value: string): string {
  return JSON.stringify(value.replaceAll("\n", " ").trim());
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`GET ${SOURCE_URL} → ${response.status}`);
}

const payload: DirectoryPayload = await response.json();
const dental = decodeRows(payload)
  .filter(clinic => clinic.categories === DENTAL_CATEGORY && Array.isArray(clinic.latlng) && clinic.latlng.length === 2)
  .sort((first, second) => first.code - second.code);
const smile = dental.filter(clinic => clinic.title.includes(SMILE_TITLE_MARKER));

const branchEntries = smile
  .map(clinic => {
    const [lat, lng] = clinic.latlng!;
    const [city = "", street = ""] = clinic.address ?? [];
    const phones = (clinic.phones ?? []).map(quote).join(", ");
    return `  { code: "${clinic.code}", title: ${quote(clinic.title)}, city: ${quote(city)}, street: ${quote(street)}, phones: [${phones}], lat: ${lat}, lng: ${lng} }`;
  })
  .join(",\n");

const coordEntries = dental
  .map(clinic => {
    const [lat, lng] = clinic.latlng!;
    return `  "${clinic.code}": [${lat}, ${lng}], // ${clinic.title.replaceAll("\n", " ")}`;
  })
  .join("\n");

const banner = `/**
 * Clalit dental-clinic directory extract, keyed by the clinic's nearme code (the number in each result
 * row's "הצגת מפה" link, nearme.clalit.co.il/nav/<code>). GENERATED by scripts/fetch-clinic-coords.ts
 * from Clalit's public directory (${SOURCE_URL}) on ${new Date().toISOString().slice(0, 10)} — do not
 * edit by hand, re-run the script instead.
 */

export interface SmileBranch {
  code: string;
  title: string;
  city: string;
  street: string;
  phones: string[];
  lat: number;
  lng: number;
}

/** Every Clalit Smile branch — the source for listing a city's branches Tamuz has no diary for. */
export const SMILE_BRANCHES: SmileBranch[] = [
`;

const coordsBanner = `];

/** Coordinates for ALL dental clinics (category ${DENTAL_CATEGORY}) — covers every result row's nav code. */
export const DENTAL_CLINIC_COORDS: Record<string, readonly [number, number]> = {
`;

writeFileSync(OUTPUT_PATH, `${banner}${branchEntries}\n${coordsBanner}${coordEntries}\n};\n`);
console.log(`Wrote ${smile.length} Smile branches + ${dental.length} dental coords to ${OUTPUT_PATH}`);
